CREATE TABLE place (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(120)     NOT NULL,
    category  VARCHAR(40)      NOT NULL,
    latitude  DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    CONSTRAINT uq_place_name UNIQUE (name),
    CONSTRAINT chk_place_latitude CHECK (latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_place_longitude CHECK (longitude BETWEEN -180 AND 180)
);

-- Composite index for the bounding-box prefilter of "places near a point".
CREATE INDEX idx_place_lat_lon ON place (latitude, longitude);
CREATE INDEX idx_place_category ON place (category);

CREATE TABLE road (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_place_id BIGINT       NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    to_place_id   BIGINT       NOT NULL REFERENCES place (id) ON DELETE CASCADE,
    name          VARCHAR(120),
    distance_m    INTEGER      NOT NULL,
    speed_kmh     INTEGER      NOT NULL,
    one_way       BOOLEAN      NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_road_distance CHECK (distance_m > 0),
    CONSTRAINT chk_road_speed CHECK (speed_kmh BETWEEN 5 AND 120),
    CONSTRAINT chk_road_not_loop CHECK (from_place_id <> to_place_id),
    -- Also serves as the index for "roads leaving a place".
    CONSTRAINT uq_road_endpoints UNIQUE (from_place_id, to_place_id)
);

-- Foreign keys are not indexed automatically in PostgreSQL; ON DELETE CASCADE needs this one.
CREATE INDEX idx_road_to_place ON road (to_place_id);
